using System.Security.Cryptography;
using Illusion.Assets.Compiled;
using Illusion.Formats.Compiled;

namespace Illusion.Diagnostics.Probes;

internal static partial class Mafia3Probes
{
    private static void VerifyCompiledEffectCurves(CompiledSceneDocument document, Action<string, bool> check)
    {
        var graph = document.Graph;
        var nodes = graph.Nodes.Where(n => n.TypeId is 0xDAE4921D or 0x205F76CC or 0x91AAAB58 or 0x6B114F89).ToArray();
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        var random = new Random(1234);
        int samples = 0;
        foreach (var node in nodes)
        {
            var curve = CompiledEffectCurve.Read(graph, node);
            for (int i = 0; i < 70; i++)
            {
                float t = i < 10 ? new float[] { -10, -1, 0, .01f, .25f, .5f, .75f, 1, 2, 10 }[i] : (float)random.NextDouble() * 10;
                float age = i < 10 ? t : (float)random.NextDouble() * 2 - .5f;
                var value = curve.Sample(t, age, false);
                hash.AppendData(BitConverter.GetBytes(value.X)); hash.AppendData(BitConverter.GetBytes(value.Y)); hash.AppendData(BitConverter.GetBytes(value.Z));
                samples++;
            }
        }
        // Digest independently generated by executing the original copied native scalar/vector
        // GetOutValueAtTimeNoLooping / GetOutValueAtTimeAndAgeNoLooping routines on the same inputs.
        check("native particle linear curves match original-binary oracle at 233450 samples", nodes.Length == 3335 && samples == 233450 &&
            Convert.ToHexString(hash.GetHashAndReset()) == "66EB8BE7516AD016A6DB8467CCC268D8E9A7FC15C0C4C30201159D1333323D99");
        var source = nodes.First(n => n.TypeId == 0xDAE4921D);
        var original = CompiledEffectCurve.Read(graph, source);
        var loop = graph.Field(source, "m_TimeLoopTransform")!;
        var fields = new[] { "m_LoopTimeStart", "m_LoopTimeDuration", "m_LoopCount" }.Select(name => graph.Field(loop, name)!).ToArray();
        var bytes = fields.Select(f => graph.Data(f).ToArray()).ToArray();
        var resource = graph.Owner(source); var before = resource.ToArray();
        try
        {
            resource.Replace(fields[0], BitConverter.GetBytes(0f)); resource.Replace(fields[1], BitConverter.GetBytes(1f)); resource.Replace(fields[2], BitConverter.GetBytes(-1));
            var infinite = CompiledEffectCurve.Read(graph, source);
            check("native particle infinite looping follows emission time modulo", infinite.Sample(2.5f) == original.Sample(.5f, looping: false));
            check("native particle looping leaves pre-start time untouched", infinite.Sample(-.25f) == original.Sample(-.25f, looping: false));
            resource.Replace(fields[2], BitConverter.GetBytes(2));
            var finite = CompiledEffectCurve.Read(graph, source);
            check("native particle finite looping resumes after final repetition", finite.Sample(4.5f) == original.Sample(2.5f, looping: false));
            resource.Replace(fields[2], BitConverter.GetBytes(int.MaxValue));
            var overflow = CompiledEffectCurve.Read(graph, source);
            check("native particle loop threshold overflows signed count before float conversion",
                overflow.Sample(.5f) == original.Sample(.5f - (float)int.MaxValue, looping: false));
            resource.Replace(fields[1], BitConverter.GetBytes(.1f)); resource.Replace(fields[2], BitConverter.GetBytes(16777217));
            var precision = CompiledEffectCurve.Read(graph, source);
            const float nearThreshold = 1677721.75f;
            check("native particle loop threshold adds count before rounding to float",
                precision.Sample(nearThreshold) == original.Sample(nearThreshold % .1f, looping: false));
            bool invalid = false;
            try { finite.Sample(float.NaN); } catch (ArgumentException) { invalid = true; }
            check("particle sampling refuses non-finite time", invalid);
        }
        finally { for (int i = 0; i < fields.Length; i++) resource.Replace(fields[i], bytes[i]); }
        check("particle curve looping tests preserve every resource byte", resource.ToArray().AsSpan().SequenceEqual(before));
        VerifyCompiledEffectBezier(document, check);
    }
}
