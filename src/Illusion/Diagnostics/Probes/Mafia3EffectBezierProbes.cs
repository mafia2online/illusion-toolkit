using System.Security.Cryptography;
using Illusion.Assets.Compiled;
using Illusion.Formats.Compiled;

namespace Illusion.Diagnostics.Probes;

internal static partial class Mafia3Probes
{
    private static void VerifyCompiledEffectBezier(CompiledSceneDocument document, Action<string, bool> check)
    {
        var graph = document.Graph;
        var nodes = graph.Nodes.Where(n => n.TypeId is 0xFC25B0BE or 0x069E546F or 0xE9A9F953 or 0x13121D82).ToArray();
        using var hash = IncrementalHash.CreateHash(HashAlgorithmName.SHA256);
        var random = new Random(1234);
        int samples = 0;
        foreach (var node in nodes)
        {
            var curve = CompiledEffectCurve.Read(graph, node);
            for (int i = 0; i < 70; i++)
            {
                float t = i < 10 ? new float[] { -10, -1, 0, .01f, .25f, .5f, .75f, 1, 2, 10 }[i] : (float)random.NextDouble() * 10;
                float age = i < 10 ? t : (float)random.NextDouble() * 2 - .5f;
                var value = curve.Sample(t, age, false);
                hash.AppendData(BitConverter.GetBytes(value.X)); hash.AppendData(BitConverter.GetBytes(value.Y)); hash.AppendData(BitConverter.GetBytes(value.Z));
                samples++;
            }
        }
        // Independently generated by the original copied scalar/vector 1D/2D native
        // entry points, including their original PrepareCurve and cubic root solver.
        check("native particle Bezier curves match original binary at 10500 samples", nodes.Length == 150 && samples == 10500 &&
            Convert.ToHexString(hash.GetHashAndReset()) == "6CF823895B624B6595EBAB282B3EE530004BDDE2E2A80720C3BB471ED951AC4E");
        var source = nodes.First(n => n.TypeId == 0xFC25B0BE);
        var resource = graph.Owner(source); var before = resource.ToArray();
        var first = graph.Items(graph.Field(source, "m_Keys"))[0];
        var valueField = graph.Field(graph.Field(first, "m_Value"), "x")!;
        byte[] original = graph.Data(valueField).ToArray();
        float valueBefore = BitConverter.ToSingle(original), changed = valueBefore + 5;
        try
        {
            resource.Replace(valueField, BitConverter.GetBytes(changed));
            check("native Bezier evaluation reads authored key changes", CompiledEffectCurve.Read(graph, source).Sample(-10000, looping: false).X == changed);
            resource.Replace(valueField, original);
            check("native Bezier evaluation returns to original after undo", CompiledEffectCurve.Read(graph, source).Sample(-10000, looping: false).X == valueBefore);
        }
        finally { resource.Replace(valueField, original); }
        var modeField = graph.Field(first, "m_Flags")!;
        var originalMode = graph.Data(modeField).ToArray();
        try
        {
            uint mode = BitConverter.ToUInt32(originalMode);
            resource.Replace(modeField, BitConverter.GetBytes((mode & ~(7u << 7)) | (7u << 7)));
            bool refused = false;
            try { CompiledEffectCurve.Read(graph, source); } catch (NotSupportedException) { refused = true; }
            check("Bezier reserved tangent mode is refused explicitly", refused);
        }
        finally { resource.Replace(modeField, originalMode); }
        check("Bezier preparation and sampling preserve all native bytes", resource.ToArray().AsSpan().SequenceEqual(before));
    }
}
